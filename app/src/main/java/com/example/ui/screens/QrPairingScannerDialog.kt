private const val QR_TAG = "QrPairingScanner"

data class ParsedPairingPayload(
    val hostName: String,
    val endpointUrl: String,
    val authToken: String
)

/**
 * Parses QR code contents generated by Google Antigravity Remote Control, Tailscale, Cloudflare
 * tunnels, JSON pairing cards, or `antigravity://pair?url=...&token=...` deep links.
 */
fun parseAntigravityPairingPayload(rawValue: String): ParsedPairingPayload? {
    val clean = rawValue.trim()
    if (clean.isEmpty()) return null

    // 1. JSON payload: {"url": "...", "token": "...", "name": "..."}
    if (clean.startsWith("{")) {
        return try {
            val json = JSONObject(clean)
            val url = json.optString("url")
                .ifBlank { json.optString("endpointUrl") }
                .ifBlank { json.optString("endpoint") }
                .trim()
            if (url.isBlank()) return null
            val token = json.optString("token")
                .ifBlank { json.optString("authToken") }
                .ifBlank { json.optString("pairingToken") }
                .trim()
            val name = json.optString("name")
                .ifBlank { json.optString("label") }
                .ifBlank { deriveHostLabelFromUrl(url) }
            ParsedPairingPayload(hostName = name, endpointUrl = url, authToken = token)
        } catch (_: Exception) {
            null
        }
    }

    // 2. Custom deep-link scheme: antigravity://pair?url=https://...&token=...&name=...
    if (clean.lowercase().startsWith("antigravity://")) {
        return try {
            val uri = Uri.parse(clean)
            val embeddedUrl = uri.getQueryParameter("url")
                ?: uri.getQueryParameter("endpoint")
                ?: return null
            val token = uri.getQueryParameter("token")
                ?: uri.getQueryParameter("auth")
                ?: ""
            val name = uri.getQueryParameter("name")
                ?.takeIf { it.isNotBlank() }
                ?: deriveHostLabelFromUrl(embeddedUrl)
            ParsedPairingPayload(
                hostName = name,
                endpointUrl = embeddedUrl.trim(),
                authToken = token.trim()
            )
        } catch (_: Exception) {
            null
        }
    }

    // 3. Direct URL: https://..., http://..., wss://..., ws://... (with optional ?token=...)
    val lower = clean.lowercase()
    if (lower.startsWith("https://") || lower.startsWith("http://") ||
        lower.startsWith("wss://") || lower.startsWith("ws://")
    ) {
        return try {
            val uri = Uri.parse(clean)
            val token = uri.getQueryParameter("token")
                ?: uri.getQueryParameter("code")
                ?: uri.getQueryParameter("auth")
                ?: ""
            ParsedPairingPayload(
                hostName = deriveHostLabelFromUrl(clean),
                endpointUrl = clean,
                authToken = token.trim()
            )
        } catch (_: Exception) {
            ParsedPairingPayload(
                hostName = "Antigravity Remote",
                endpointUrl = clean,
                authToken = ""
            )
        }
    }

    return null
}

private fun deriveHostLabelFromUrl(url: String): String {
    return try {
        val host = Uri.parse(url).host.orEmpty()
        if (host.isNotBlank()) "Antigravity ($host)" else "Antigravity Remote"
    } catch (_: Exception) {
        "Antigravity Remote"
    }
}

@OptIn(ExperimentalGetImage::class)
@Composable
fun QrPairingScannerDialog(
    onPairingScanned: (ParsedPairingPayload) -> Unit,
    onDismiss: () -> Unit
) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current
    val appearance = LocalAppearanceSettings.current
    val bg = appearance.backgroundColor
    val surface = appearance.surfaceColor
    val fg = appearance.foregroundColor
    val secondaryFg = appearance.secondaryTextColor
    val accent = appearance.accentColor

    var hasCameraPermission by remember {
        mutableStateOf(
            ContextCompat.checkSelfPermission(
                context,
                Manifest.permission.CAMERA
            ) == PackageManager.PERMISSION_GRANTED
        )
    }
    var torchEnabled by remember { mutableStateOf(false) }
    var activeCamera by remember { mutableStateOf<Camera?>(null) }
    var statusMessage by remember { mutableStateOf("Align the Google Antigravity Remote QR code inside the frame") }
    val scanDelivered = remember { AtomicBoolean(false) }
    val analyzerExecutor = remember { Executors.newSingleThreadExecutor() }

    val cameraPermissionLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.RequestPermission()
    ) { granted ->
        hasCameraPermission = granted
    }

    LaunchedEffect(Unit) {
        if (!hasCameraPermission) {
            cameraPermissionLauncher.launch(Manifest.permission.CAMERA)
        }
    }

    DisposableEffect(Unit) {
        onDispose {
            analyzerExecutor.shutdown()
        }
    }

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            modifier = Modifier
                .fillMaxSize()
                .testTag("qr_pairing_scanner_dialog"),
            color = bg
        ) {
            Column(modifier = Modifier.fillMaxSize()) {
                // Header
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .background(surface)
                        .padding(horizontal = 16.dp, vertical = 14.dp),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(
                            imageVector = Icons.Default.QrCodeScanner,
                            contentDescription = null,
                            tint = accent,
                            modifier = Modifier.size(22.dp)
                        )
                        Spacer(modifier = Modifier.width(10.dp))
                        Column {
                            Text(
                                text = "Scan Antigravity QR Code",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Bold,
                                color = fg
                            )
                            Text(
                                text = "Instant host URL & pairing token import",
                                style = MaterialTheme.typography.labelSmall,
                                color = secondaryFg
                            )
                        }
                    }

                    Row(verticalAlignment = Alignment.CenterVertically) {
                        if (hasCameraPermission && activeCamera?.cameraInfo?.hasFlashUnit() == true) {
                            IconButton(
                                onClick = {
                                    torchEnabled = !torchEnabled
                                    activeCamera?.cameraControl?.enableTorch(torchEnabled)
                                },
                                modifier = Modifier.testTag("qr_torch_toggle_button")
                            ) {
                                Icon(
                                    imageVector = if (torchEnabled) Icons.Default.FlashOn else Icons.Default.FlashOff,
                                    contentDescription = "Toggle Flashlight",
                                    tint = if (torchEnabled) accent else secondaryFg
                                )
                            }
                        }
                        IconButton(
                            onClick = onDismiss,
                            modifier = Modifier.testTag("qr_scanner_close_button")
                        ) {
                            Icon(
                                imageVector = Icons.Default.Close,
                                contentDescription = "Close QR Scanner",
                                tint = fg
                            )
                        }
                    }
                }

                // CameraX Preview + ML Kit Barcode Analyzer
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth(),
                    contentAlignment = Alignment.Center
                ) {
                    if (hasCameraPermission) {
                        AndroidView(
                            factory = { ctx ->
                                val previewView = PreviewView(ctx).apply {
                                    scaleType = PreviewView.ScaleType.FILL_CENTER
                                }
                                val cameraProviderFuture = ProcessCameraProvider.getInstance(ctx)
                                cameraProviderFuture.addListener({
                                    try {
                                        val cameraProvider = cameraProviderFuture.get()
                                        val preview = Preview.Builder().build().also {
                                            it.surfaceProvider = previewView.surfaceProvider
                                        }

                                        val options = BarcodeScannerOptions.Builder()
                                            .setBarcodeFormats(Barcode.FORMAT_QR_CODE)
                                            .build()
                                        val barcodeScanner = BarcodeScanning.getClient(options)

                                        val imageAnalysis = ImageAnalysis.Builder()
                                            .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                                            .build()

                                        imageAnalysis.setAnalyzer(analyzerExecutor) { imageProxy ->
                                            val mediaImage = imageProxy.image
                                            if (mediaImage != null && !scanDelivered.get()) {
                                                val inputImage = InputImage.fromMediaImage(
                                                    mediaImage,
                                                    imageProxy.imageInfo.rotationDegrees
                                                )
                                                barcodeScanner.process(inputImage)
                                                    .addOnSuccessListener { barcodes ->
                                                        for (barcode in barcodes) {
                                                            val raw = barcode.rawValue ?: continue
                                                            val parsed = parseAntigravityPairingPayload(raw)
                                                            if (parsed != null && scanDelivered.compareAndSet(false, true)) {
                                                                ContextCompat.getMainExecutor(ctx).execute {
                                                                    onPairingScanned(parsed)
                                                                }
                                                                break
                                                            } else if (parsed == null) {
                                                                statusMessage = "QR detected, waiting for valid https://, wss://, or Antigravity pairing payload..."
                                                            }
                                                        }
                                                    }
                                                    .addOnCompleteListener {
                                                        imageProxy.close()
                                                    }
                                            } else {
                                                imageProxy.close()
                                            }
                                        }

                                        cameraProvider.unbindAll()
                                        activeCamera = cameraProvider.bindToLifecycle(
                                            lifecycleOwner,
                                            CameraSelector.DEFAULT_BACK_CAMERA,
                                            preview,
                                            imageAnalysis
                                        )
                                    } catch (e: Exception) {
                                        Log.e(QR_TAG, "Failed to bind CameraX QR scanner", e)
                                        statusMessage = "Camera preview unavailable on this device: ${e.localizedMessage}"
                                    }
                                }, ContextCompat.getMainExecutor(ctx))
                                previewView
                            },
                            modifier = Modifier.fillMaxSize()
                        )

                        // Viewfinder Reticle Overlay
                        Box(
                            modifier = Modifier
                                .size(250.dp)
                                .clip(RoundedCornerShape(24.dp))
                                .border(2.5.dp, EmeraldOnline, RoundedCornerShape(24.dp))
                        )

                        Box(
                            modifier = Modifier
                                .align(Alignment.BottomCenter)
                                .padding(24.dp)
                                .clip(RoundedCornerShape(14.dp))
                                .background(Color.Black.copy(alpha = 0.72f))
                                .padding(horizontal = 16.dp, vertical = 10.dp)
                        ) {
                            Text(
                                text = statusMessage,
                                style = MaterialTheme.typography.bodyMedium,
                                color = Color.White,
                                textAlign = TextAlign.Center
                            )
                        }
                    } else {
                        Column(
                            modifier = Modifier.padding(28.dp),
                            horizontalAlignment = Alignment.CenterHorizontally,
                            verticalArrangement = Arrangement.spacedBy(12.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.QrCodeScanner,
                                contentDescription = null,
                                tint = accent,
                                modifier = Modifier.size(48.dp)
                            )
                            Text(
                                text = "Camera Access Needed for QR Pairing",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Bold,
                                color = fg,
                                textAlign = TextAlign.Center
                            )
                            Text(
                                text = "Grant camera access to scan your Google Antigravity desktop Remote QR code automatically. You can still paste your URL manually anytime.",
                                style = MaterialTheme.typography.bodyMedium,
                                color = secondaryFg,
                                textAlign = TextAlign.Center
                            )
                            Spacer(modifier = Modifier.height(4.dp))
                            Button(
                                onClick = { cameraPermissionLauncher.launch(Manifest.permission.CAMERA) },
                                colors = ButtonDefaults.buttonColors(
                                    containerColor = accent,
                                    contentColor = Color(0xFF070708)
                                ),
                                modifier = Modifier.testTag("request_camera_permission_button")
                            ) {
                                Text("Grant Camera Permission", fontWeight = FontWeight.Bold)
                            }
                        }
                    }
                }
            }
        }
    }
}
